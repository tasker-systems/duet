#!/usr/bin/env bash
# Witness for scripts/capture-fixtures.sh's fixtures target: regenerating the fixtures never deletes
# a committed file it does not generate, and still replaces every file it does.
#
# It runs a copy of the script in a scratch tree that mirrors the repository's layout (the script
# finds the fixtures from its own location), seeded with the committed fixtures, with:
#   - keep-me.txt, a committed fixture the script does not generate, which must survive byte for byte;
#   - crates/duet-dsp/tests/fixtures/pyin-scale.txt, the recorded pyin reading, which must survive;
#   - every generated file overwritten with a stale marker, each of which must be replaced.
# Fakes stand in for uname (so it runs off macOS), lame, flac, oggenc and afconvert: each writes a
# marker to its output path. python3 is real.
#
# NOT CHECKED: the real encoders' output, or that the generated bytes match the committed ones.
#
# CAPTURE_SCRIPT=<file> runs the cases against another copy of capture-fixtures.sh, such as main's,
# to show they fail without this change. CI runs this in .github/workflows/ci.yml#gate.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/.." && pwd)"
script="${CAPTURE_SCRIPT:-$here/capture-fixtures.sh}"
scratch="$(mktemp -d "${TMPDIR:-/tmp}/capture-fixtures-test.XXXXXX")"
trap 'rm -rf "$scratch"' EXIT

failures=0
ok() { echo "ok   $1"; }
bad() { echo "FAIL $1"; failures=$((failures + 1)); }

# The fakes: uname answers Darwin; each encoder writes "fake <tool>" to the path after -o, or to its
# last argument.
bin="$scratch/bin"
mkdir -p "$bin"
printf '#!/usr/bin/env bash\necho Darwin\n' > "$bin/uname"
for tool in lame flac oggenc afconvert; do
  cat > "$bin/$tool" <<EOF
#!/usr/bin/env bash
out="\${!#}"
while (( \$# )); do [[ "\$1" == -o ]] && { out="\$2"; break; }; shift; done
echo "fake $tool" > "\$out"
EOF
done
chmod +x "$bin"/*
export PATH="$bin:$PATH"

tree="$scratch/repo"
fixtures="$tree/crates/duet-capture/tests/fixtures"
dsp="$tree/crates/duet-dsp/tests/fixtures"
mkdir -p "$tree/scripts" "$fixtures" "$dsp"
cp "$script" "$tree/scripts/capture-fixtures.sh"
cp "$root"/crates/duet-capture/tests/fixtures/* "$fixtures/"
cp "$root"/crates/duet-dsp/tests/fixtures/* "$dsp/"

# Every committed file in the fixtures directory is generated (the script's header lists them), so
# each is made stale; keep-me.txt stands for a committed fixture added later.
generated=()
for f in "$fixtures"/*; do generated+=("$(basename "$f")"); echo stale > "$f"; done
echo "a committed fixture the script does not generate" > "$fixtures/keep-me.txt"
cp "$fixtures/keep-me.txt" "$scratch/keep-me.expected"
cp "$dsp/pyin-scale.txt" "$scratch/pyin-scale.expected"

if bash "$tree/scripts/capture-fixtures.sh" fixtures > "$scratch/out" 2>&1; then
  ok "capture-fixtures.sh fixtures runs"
else
  bad "capture-fixtures.sh fixtures runs"; cat "$scratch/out"
fi

if [[ -f "$fixtures/keep-me.txt" ]] && cmp -s "$fixtures/keep-me.txt" "$scratch/keep-me.expected"; then
  ok "a committed fixture it does not generate survives, byte for byte"
else
  bad "a committed fixture it does not generate survives, byte for byte"
fi
if cmp -s "$dsp/pyin-scale.txt" "$scratch/pyin-scale.expected"; then
  ok "pyin-scale.txt survives, byte for byte"
else
  bad "pyin-scale.txt survives, byte for byte"
fi

echo stale > "$scratch/stale.ref"
stale=()
for f in "${generated[@]}"; do
  [[ -f "$fixtures/$f" ]] && ! cmp -s "$fixtures/$f" "$scratch/stale.ref" || stale+=("$f")
done
if (( ${#stale[@]} == 0 )); then
  ok "every generated file (${#generated[@]}) is replaced"
else
  bad "every generated file is replaced; still stale or missing: ${stale[*]}"
fi

if (( failures )); then echo "$failures failed"; exit 1; fi
echo "all passed"
